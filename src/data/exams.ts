export function getExamsByCategory(categorySlug: string): Exam[] {
  return exams.filter((e) => e.categorySlug === categorySlug);
}

export function getExamBySlug(slug: string): Exam | undefined {
  return exams.find((e) => e.slug === slug);
}

export function getCategoryBySlug(slug: string): ExamCategory | undefined {
  return categories.find((c) => c.slug === slug);
}

export function getFeaturedExams(): Exam[] {
  return exams.filter((e) => e.featured);
}

export function searchExams(query: string): Exam[] {
  const q = query.toLowerCase().trim();
  if (!q) return exams;
  return exams.filter(
    (e) =>
      e.name.toLowerCase().includes(q) ||
      e.category.toLowerCase().includes(q) ||
      e.description.toLowerCase().includes(q) ||
      (e.provider && e.provider.toLowerCase().includes(q)) ||
      e.keywords.some((k) => k.toLowerCase().includes(q))
  );
}
